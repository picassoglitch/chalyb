#!/usr/bin/env node
// pnpm legal:hash — fingerprints the legal documents every consent event
// cites (aceptacion-ux §10.2 `documents`) and archives each document's
// current version as a module the site renders from:
//   src/content/legal/archive/<doc>/v<x-y>.ts
//     source    Law's Markdown, as written
//     template  the same with every amount swapped for its pricing.ts role
//               ({{mxn:pro_month}}); an amount no role explains, or one that
//               two roles explain without registry.json `amountRoles`, fails
//     rendered  the template filled with today's prices: the text people see
//     sha256    of `rendered`, the hash consent events cite
//   src/content/legal/archive/index.ts          (static import map)
//   src/lib/legal/document-hashes.json          (current version's hash)
//   src/lib/legal/publish-state.json            (what the publish gate reads)
//
// Versions live in src/lib/legal/registry.json. A version marked
// `published: true` is frozen as it was accepted: this script never rewrites
// it, and fails if its Markdown changed or if today's prices would render it
// differently. Either one needs a new version. Drafts are rewritten freely.

import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
// Run through tests/ts-resolve.mjs (see package.json) so the amount roles
// come straight from src/config/pricing.ts.
import { bindAmounts, tokenizeAmounts } from '../src/lib/legal/amounts.ts';

const root = new URL('../', import.meta.url);
const DOCS = new URL('docs/design/app-reimagine/legal/', root);
const ARCHIVE = new URL('src/content/legal/archive/', root);
const registry = JSON.parse(readFileSync(new URL('src/lib/legal/registry.json', root), 'utf8'));

const sha = (text) => createHash('sha256').update(text).digest('hex');
const vslug = (v) => `v${v.replace(/\./g, '-')}`;
const field = (text, name) => {
  const m = new RegExp(`export const ${name}: string = (".*");\\n`).exec(text);
  return m ? JSON.parse(m[1]) : null;
};

const hashes = {};
let failed = false;
for (const [doc, entry] of Object.entries(registry)) {
  const meta = entry.versions[entry.current] ?? {};
  const dir = new URL(`${doc}/`, ARCHIVE);
  mkdirSync(dir, { recursive: true });
  const file = new URL(`${vslug(entry.current)}.ts`, dir);
  const source = readFileSync(new URL(entry.file, DOCS), 'utf8');

  if (meta.published && existsSync(file)) {
    const prev = readFileSync(file, 'utf8');
    const prevSource = field(prev, 'source');
    const prevRendered = field(prev, 'rendered');
    if (prevSource !== source) {
      console.error(
        `✗ ${doc} ${entry.current} is published and its Markdown changed. Add a new version first.`,
      );
      failed = true;
    } else if (bindAmounts(field(prev, 'template')) !== prevRendered) {
      console.error(
        `✗ ${doc} ${entry.current} is published and today's prices render it differently. Add a new version.`,
      );
      failed = true;
    }
    hashes[doc] = /sha256: string = '([0-9a-f]{64})'/.exec(prev)?.[1];
    continue;
  }

  let template;
  try {
    template = tokenizeAmounts(source, meta.amountRoles ?? {}).template;
  } catch (e) {
    console.error(`✗ ${doc}: ${e.message}`);
    failed = true;
    continue;
  }
  const rendered = bindAmounts(template);
  const digest = sha(rendered);
  hashes[doc] = digest;
  writeFileSync(
    file,
    `// Generated by \`pnpm legal:hash\` from docs/design/app-reimagine/legal/${entry.file}.\n` +
      `// Do not edit: change the Markdown and re-run the script.\n\n` +
      `export const version = '${entry.current}';\n` +
      `export const sha256: string = '${digest}';\n` +
      `export const source: string = ${JSON.stringify(source)};\n` +
      `export const template: string = ${JSON.stringify(template)};\n` +
      `export const rendered: string = ${JSON.stringify(rendered)};\n`,
  );
}
if (failed) process.exit(1);

// Every archived version stays importable, current or not.
const imports = [];
const map = [];
for (const [doc, entry] of Object.entries(registry)) {
  const rows = [];
  for (const v of Object.keys(entry.versions)) {
    if (!existsSync(new URL(`${doc}/${vslug(v)}.ts`, ARCHIVE))) continue;
    const id = `${doc}_${vslug(v).replace(/-/g, '_')}`;
    imports.push(`import * as ${id} from './${doc}/${vslug(v)}';`);
    rows.push(`    '${v}': ${id},`);
  }
  map.push(`  ${doc}: {\n${rows.join('\n')}\n  },`);
}
writeFileSync(
  new URL('index.ts', ARCHIVE),
  `// Generated by \`pnpm legal:hash\`. Every archived legal version, by document.\n\n` +
    `${imports.join('\n')}\n\n` +
    `export interface ArchivedVersion {\n  version: string;\n  sha256: string;\n  source: string;\n  template: string;\n  rendered: string;\n}\n\n` +
    `export const ARCHIVE: Record<string, Record<string, ArchivedVersion>> = {\n${map.join('\n')}\n};\n`,
);
writeFileSync(
  new URL('src/lib/legal/document-hashes.json', root),
  `${JSON.stringify(hashes, null, 2)}\n`,
);
console.log(hashes);

// What the publish gate reads (flags.ts stays import-free apart from this
// small JSON): per document, the current version, whether it's marked
// published and how many bracket placeholders its rendered text still has.
const { LEGAL_DOCS, currentVersion, placeholders, versionMeta } =
  await import('../src/lib/legal/registry.ts');
const state = Object.fromEntries(
  LEGAL_DOCS.map((doc) => [
    doc,
    {
      version: currentVersion(doc),
      published: Boolean(versionMeta(doc)?.published),
      placeholders: placeholders(doc).length,
    },
  ]),
);
writeFileSync(
  new URL('src/lib/legal/publish-state.json', root),
  `${JSON.stringify(state, null, 2)}\n`,
);
